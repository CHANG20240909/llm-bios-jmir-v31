"""
Phase 2 LLM Agent Pipeline.

Reads Phase 1 scored CSV, extracts WARN/FAIL alarm cases, sends them to the
LLM agent, and produces JSONL (machine) + TXT (expert review) reports.

Usage:
    python phase2_pipeline.py --config ../configs/phase2_llm_agent.yaml
    python phase2_pipeline.py --config ../configs/phase2_llm_agent.yaml --dry-run
"""

import argparse
import json
import os
import sys
from datetime import datetime

import omegaconf
import pandas as pd
from tqdm import tqdm

try:
    from dotenv import load_dotenv
    load_dotenv()
except ImportError:
    pass

from llm_agent import AlarmCase, LLMVerdict, call_llm, dry_run_verdict


def load_alarm_cases(csv_path):
    """Load Phase 1 scored CSV and extract alarm cases."""
    df = pd.read_csv(csv_path)

    if "alarm_level" not in df.columns:
        print("[ERROR] 'alarm_level' column not found in CSV.")
        print("  The CSV must be generated by the updated screen_outputs.py (Phase 1).")
        print("  Re-run: python screen_outputs.py --config <your_config.yaml>")
        sys.exit(1)

    total = len(df)

    # Use phase15_alarm_level (Phase 1.5 result) if available, else fall back to alarm_level.
    # This ensures Phase 2 only processes cases not resolved by Phase 1.5.
    alarm_col = "phase15_alarm_level" if "phase15_alarm_level" in df.columns else "alarm_level"
    if alarm_col == "phase15_alarm_level":
        print(f"[Phase 2] Using phase15_alarm_level (Phase 1.5 results) for alarm filtering.")

    alarm_df = df[df[alarm_col].isin(["WARN", "FAIL"])].copy()
    pass_df = df[df[alarm_col] == "PASS"]

    print(f"[Phase 2] Loaded {total} triples from Phase 1 scored CSV")
    print(f"  PASS (skipped) : {len(pass_df)}")
    print(f"  Alarm (to LLM) : {len(alarm_df)}  {sorted(alarm_df[alarm_col].unique().tolist())}")

    cases = []
    for _, row in alarm_df.iterrows():
        fail_locs = str(row.get("fail_locations", "")).split(";") if pd.notna(row.get("fail_locations")) else []
        fail_locs = [f.strip() for f in fail_locs if f.strip()]

        origin_cands = str(row.get("origin_candidates", "")).split(";") if pd.notna(row.get("origin_candidates")) else []
        origin_cands = [c.strip() for c in origin_cands if c.strip()]

        target_cands = str(row.get("target_candidates", "")).split(";") if pd.notna(row.get("target_candidates")) else []
        target_cands = [c.strip() for c in target_cands if c.strip()]

        phase1_alarm = str(row.get(alarm_col, row.get("alarm_level", "FAIL")))
        case = AlarmCase(
            source_sentence=str(row.get("source_sentence", "")) if pd.notna(row.get("source_sentence")) else "",
            origin=str(row["origin"]),
            relationship=str(row["relationship"]),
            target=str(row["target"]),
            phase1_alarm=phase1_alarm,
            phase1_fail_locations=fail_locs,
            origin_status=str(row.get("origin_status", "")) if pd.notna(row.get("origin_status")) else "",
            origin_candidates=origin_cands,
            target_status=str(row.get("target_status", "")) if pd.notna(row.get("target_status")) else "",
            target_candidates=target_cands,
        )
        cases.append(case)

    return cases


def format_report_case(idx, case, verdict):
    """Format a single case for the TXT expert review report."""
    sep = "=" * 70
    sub = "-" * 70
    icon = {"PASS": "[OK]", "WARN": "[??]", "FAIL": "[!!]"}

    src_preview = case.source_sentence[:100] + "..." if len(case.source_sentence) > 100 else case.source_sentence

    lines = [
        sep,
        f"  Case #{idx+1}  |  Phase1 alarm: {case.phase1_alarm}  →  LLM verdict: {verdict.verdict} {icon.get(verdict.verdict, '[??]')}",
        sub,
        f'  Source : "{src_preview}"' if src_preview else "  Source : (not available)",
        f"  Triple : {case.origin} -- {case.relationship} -- {case.target}",
        sub,
        f"  [Phase 1 alarm]  fail_locations: {', '.join(case.phase1_fail_locations) if case.phase1_fail_locations else 'n/a'}",
    ]

    for label, status, cands in [
        ("origin", case.origin_status, case.origin_candidates),
        ("target", case.target_status, case.target_candidates),
    ]:
        if status in ("WARN", "FAIL"):
            best_match = cands[0] if cands else "?"
            lines.append(
                f'    {label:8s}: "{getattr(case, label)}"  →  status={status}  best_match="{best_match}"'
            )
            lines.append(f"    candidates: {cands}")

    lines.extend([
        sub,
        f"  [LLM verdict]  {verdict.verdict}",
        f"  Reasoning      : {verdict.reasoning}",
        f"  Origin assess  : {verdict.origin_assessment}",
        f"  Target assess  : {verdict.target_assessment}",
        f"  Modifier change: {verdict.modifier_changes_meaning}",
    ])

    if verdict.error:
        lines.append(f"  ERROR: {verdict.error}")

    lines.extend([
        sub,
        f"  [ ] Expert confirmed PASS    [ ] Expert confirmed FAIL    [ ] Needs more review",
        sep,
    ])

    return "\n".join(lines)


def run_pipeline(config_path, dry_run=False):
    config = omegaconf.OmegaConf.load(config_path)

    scored_csv = config.phase2.scored_csv
    output_jsonl = config.phase2.output_jsonl
    output_report = config.phase2.output_report
    model = config.phase2.get("model", "gpt-4o")

    cases = load_alarm_cases(scored_csv)

    if not cases:
        print("[Phase 2] No alarm cases found. Nothing to process.")
        return

    results = []
    for i, case in enumerate(tqdm(cases, desc="LLM agent")):
        if dry_run:
            verdict = dry_run_verdict(case)
        else:
            verdict = call_llm(case, model=model)

        record = {
            "source_sentence": case.source_sentence,
            "origin": case.origin,
            "relationship": case.relationship,
            "target": case.target,
            "phase1_alarm": case.phase1_alarm,
            "phase1_fail_locations": case.phase1_fail_locations,
            "origin_status": case.origin_status,
            "origin_candidates": case.origin_candidates,
            "target_status": case.target_status,
            "target_candidates": case.target_candidates,
            "llm_verdict": verdict.verdict,
            "llm_reasoning": verdict.reasoning,
            "llm_origin_assessment": verdict.origin_assessment,
            "llm_target_assessment": verdict.target_assessment,
            "llm_modifier_changes_meaning": verdict.modifier_changes_meaning,
            "llm_direction_correct": verdict.direction_correct,
            "llm_evidence_tier": verdict.evidence_tier,
            "llm_suggested_origin": verdict.suggested_origin,
            "llm_suggested_target": verdict.suggested_target,
            "llm_error": verdict.error,
        }
        results.append((case, verdict, record))

        icon = {"PASS": "[OK]", "WARN": "[??]", "FAIL": "[!!]"}
        print(f"  {case.origin} -- {case.relationship} -- {case.target}")
        print(f"    Phase1: {case.phase1_alarm}  →  LLM: {verdict.verdict} {icon.get(verdict.verdict, '')}")

    os.makedirs(os.path.dirname(output_jsonl) if os.path.dirname(output_jsonl) else ".", exist_ok=True)
    with open(output_jsonl, "w", encoding="utf-8") as f:
        for _, _, record in results:
            f.write(json.dumps(record, ensure_ascii=False) + "\n")
    print(f"\n[Phase 2] JSONL saved: {output_jsonl}")

    verdict_counts = {}
    for _, v, _ in results:
        verdict_counts[v.verdict] = verdict_counts.get(v.verdict, 0) + 1

    report_lines = [
        "=" * 70,
        "  Phase 2 LLM Agent Expert Review Report",
        f"  Generated : {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}",
        f"  Mode      : {'DRY RUN' if dry_run else model}",
        f"  Cases     : {len(results)}",
        "=" * 70,
        "",
        "  LLM Verdict Summary",
    ]
    for v_label in ["PASS", "WARN", "FAIL"]:
        report_lines.append(f"    {v_label} : {verdict_counts.get(v_label, 0)}")
    report_lines.extend([
        "",
        "  NOTE: LLM verdicts are SUGGESTIONS only.",
        "        Final decisions must be made by a qualified expert.",
        "",
    ])

    for i, (case, verdict, _) in enumerate(results):
        report_lines.append("")
        report_lines.append(format_report_case(i, case, verdict))

    with open(output_report, "w", encoding="utf-8") as f:
        f.write("\n".join(report_lines))
    print(f"[Phase 2] Report saved: {output_report}")


def main():
    parser = argparse.ArgumentParser(description="Phase 2 LLM Agent Pipeline")
    parser.add_argument("--config", required=True, help="Phase 2 config YAML path")
    parser.add_argument("--dry-run", action="store_true", help="Skip API calls, echo Phase 1 verdicts")
    args = parser.parse_args()

    run_pipeline(args.config, dry_run=args.dry_run)


if __name__ == "__main__":
    main()
